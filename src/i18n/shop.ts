export const shopLanguageTag: Record<Locale, string> = {
  vi: "vi-VN",
  en: "en-US",
  ja: "ja-JP",
  zh: "zh-CN",
};

export const getShopCopy = (locale: Locale) => shopCopy[locale];

export function formatMoney(amountMinor: number, currency: string, locale: Locale): string {
  const formatter = new Intl.NumberFormat(shopLanguageTag[locale], {
    style: "currency",
    currency: currency.toUpperCase(),
    currencyDisplay: "symbol",
  });
  const fractionDigits = formatter.resolvedOptions().maximumFractionDigits ?? 2;
  return formatter.format(amountMinor / (10 ** fractionDigits));
}

export function formatProductPrice(product: ProductViewModel, locale: Locale): string {
  const copy = getShopCopy(locale);
  const minimum = formatMoney(product.minPriceMinor, product.currency, locale);
  if (product.minPriceMinor === product.maxPriceMinor) return minimum;
  const maximum = formatMoney(product.maxPriceMinor, product.currency, locale);
  return copy.card.priceRange.replace("{min}", minimum).replace("{max}", maximum);
}

export function formatProductCount(locale: Locale, count: number): string {
  return getShopCopy(locale).productCount.replace("{count}", new Intl.NumberFormat(shopLanguageTag[locale]).format(count));
}

function formatShopDateValue(value: string | null | undefined, locale: Locale, options: Intl.DateTimeFormatOptions): string {
  if (!value) return "—";
  const date = new Date(value);
  if (!Number.isFinite(date.getTime())) return "—";
  return new Intl.DateTimeFormat(shopLanguageTag[locale], options).format(date);
}

export function formatShopDate(value: string | null | undefined, locale: Locale): string {
  return formatShopDateValue(value, locale, { dateStyle: "medium" });
}

export function formatShopDateTime(value: string | null | undefined, locale: Locale): string {
  return formatShopDateValue(value, locale, { dateStyle: "medium", timeStyle: "short" });
}

export function formatShopOrderStatus(status: string | null | undefined, locale: Locale): string {
  const labels = getShopCopy(locale).account.status.order as Record<string, string>;
  return labels[String(status || "")] || getShopCopy(locale).account.status.unknown;
}

